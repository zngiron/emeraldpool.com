<details class="wp-block-details"><summary>What electrical work does a hot tub need?</summary><!-- wp:paragraph -->
<p>Most full-size models need a dedicated 50 amp GFCI circuit within sight of the spa. Plug-in 120V models exist and heat more slowly. We will tell you which you are looking at before you order, and we can recommend an electrician in Eugene or Bend.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What does the spa sit on?"} -->
<details class="wp-block-details"><summary>What does the spa sit on?</summary><!-- wp:paragraph -->
<p>A level, load-rated surface: a four-inch reinforced concrete pad, a properly built deck, or a spa pad system. A filled seven-seat spa weighs about three tons, so this is the one part of the job worth doing before delivery day.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How much does it cost to run through an Oregon winter?"} -->
<details class="wp-block-details"><summary>How much does it cost to run through an Oregon winter?</summary><!-- wp:paragraph -->
<p>For a well-insulated model with a tight cover, most customers report between fifteen and forty dollars a month. Cover condition matters more than any other single factor, which is why we replace covers rather than talk you into a new spa.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How long from order to first soak?"} -->
<details class="wp-block-details"><summary>How long from order to first soak?</summary><!-- wp:paragraph -->
<p>If the model is on our floor, usually one to two weeks. A special order runs six to ten. We give you a delivery window when you order, not after.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Do you take trade-ins?"} -->
<details class="wp-block-details"><summary>Do you take trade-ins?</summary><!-- wp:paragraph -->
<p>Sometimes, depending on the age and condition of the spa and whether we can move it safely. Send a photograph and the model number through the contact page and we will tell you honestly.</p>
